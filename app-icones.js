// =========================================================================
// 2. MOTOR DE AUTO-SELEÇÃO INTELIGENTE (AUTO-MATCH 100% EMOJIS)
// =========================================================================
window.analisarTituloEAutoSelecionarIcone = function(tituloOriginal, iconeAtualizado) {
    if (!tituloOriginal || typeof tituloOriginal !== "string") {
        return iconeAtualizado || "⭐";
    }

    const stopwords = [
        "a", "o", "e", "de", "do", "da", "em", "para", "com", "no", "na",
        "um", "uma", "os", "as", "que", "se", "por", "dos", "das", "meu",
        "minha", "seu", "sua", "pela", "pelo", "pro", "pra", "ao", "aos"
    ];

    const texto = tituloOriginal
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .replace(/[^a-z0-9\s]/g, "");

    const palavras = texto.split(/\s+/).filter(p => p.length > 2 && !stopwords.includes(p));

    // 1ª Passagem: Correspondência exata da palavra nas tags
    for (const palavra of palavras) {
        for (const item of window.CatalogoEmojisSuiri) {
            const arrayTags = item.tags.split(" ");
            if (arrayTags.includes(palavra)) {
                return item.emoji;
            }
        }
    }

    // 2ª Passagem: Correspondência por prefixo/inclusão parcial (ex: "lavando" -> "lavar")
    for (const palavra of palavras) {
        const radical = palavra.substring(0, 4);
        for (const item of window.CatalogoEmojisSuiri) {
            if (item.tags.includes(radical)) {
                return item.emoji;
            }
        }
    }

    return iconeAtualizado || "⭐";
};

// Retrocompatibilidade
window.obterEmojiConcordanteKids = window.analisarTituloEAutoSelecionarIcone;

// =========================================================================
// 3. ATUALIZAÇÃO VISUAL EM TEMPO REAL (ONINPUT DO TÍTULO)
// =========================================================================
window.acionarAutoMatchTituloMissao = function(titulo, contexto) {
    const inputIcone = document.getElementById(`input-${contexto}-missao-icone`);
    const spanPreview = document.getElementById(`svg-preview-${contexto}-missao`);

    if (!inputIcone || !spanPreview) return;

    const iconeAtual = inputIcone.value;
    const emojiDetectado = window.analisarTituloEAutoSelecionarIcone(titulo, iconeAtual);

    if (emojiDetectado && emojiDetectado !== iconeAtual && titulo.trim().length >= 2) {
        inputIcone.value = emojiDetectado;
        spanPreview.innerHTML = `<span style="font-size:32px; line-height:1; user-select:none;">${emojiDetectado}</span>`;
    }
};

