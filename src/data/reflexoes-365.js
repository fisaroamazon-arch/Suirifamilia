window.obterReflexaoEstoicaDoDia = function(data = new Date()) {
    const meses = ['janeiro','fevereiro','março','abril','maio','junho','julho','agosto','setembro','outubro','novembro','dezembro'];
    // 29 de fevereiro reutiliza 28 de fevereiro, mantendo as datas seguintes.
    const dia=data.getMonth()===1&&data.getDate()===29?28:data.getDate();
    return window.AcervoReflexoesEstoicas365.find(r=>r.data===`${dia} de ${meses[data.getMonth()]}`);
};
